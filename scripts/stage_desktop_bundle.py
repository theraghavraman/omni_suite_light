"""
OmniConverter Studio — desktop base bundle + optional component builder
(scripts/stage_desktop_bundle.py)

The desktop installer is small: the Electron shell, the Local Engine code, the Studio UI and
the SHA-256-verified offline browser assets. Everything heavy is an optional *component*
the user picks in the Component Manager on first launch (or later):

    python-runtime      relocatable CPython 3.12 (python-build-standalone, pinned)
    python-libraries    requirements-local.txt installed for that runtime (site-packages)
    libreoffice, calibre, ffmpeg, poppler, qpdf, imagemagick, ghostscript, tesseract,
    pandoc, 7zip, rsvg, yt-dlp   native tools with their libraries and data

This script builds, for the current platform:

    build/omni-engine/                     base resources (engine, UI, vendor/ assets)
    build/components/<platform>/<id>/      staged, relocated, probed and audited component
    out/components/<platform>/<id>-<platform>.tar.gz   archive the app downloads
    build/components-catalog.json          id, version, size, SHA-256, tools, dependencies
                                           (shipped inside the installer; the app refuses any
                                           download that does not match it)
    build/BUNDLE_MANIFEST.json             staging record (versions, probes, audit)

The same command runs for `npm run desktop:make` and in CI. It exits 1 if any component is
missing, fails its checksum, does not execute, or still refers to build-machine paths, and
electron/forge.config.cjs refuses to package an incomplete build. Pinned inputs live in
scripts/desktop_bundle_sources.json.
"""
