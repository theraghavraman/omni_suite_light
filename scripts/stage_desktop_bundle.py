def build_native_component(comp: dict, comp_root: Path, platform_spec: dict, sources: dict, cache_dir: Path) -> dict:
    tools: dict[str, dict] = {}
    env: dict[str, list[str]] = {}
    licenses: list[dict] = []
    relocated: list[str] = []
    for spec in platform_spec.get("downloads", []):
        if spec.get("component") != comp["id"]:
            continue
        algo, expected = digest_of(spec)
        archive = download_verified(_spec_urls(spec), algo, expected, cache_dir, spec["id"])
        log(f"{comp['id']}: extracting {spec['id']} ({spec['format']})")
        extract_download(spec, archive, comp_root / spec["dest"])
        for name, ref in spec.get("tools", {}).items():
            exe = _resolve_tool_ref(ref, comp_root)
            tools[name] = {"path": _posix_rel(exe, comp_root), "source": spec["url"], "version": spec["version"]}
            if name == "7z" and os.name == "nt":
                _SEVENZIP["7z"] = exe
        licenses.append({"id": spec["id"], "version": spec["version"], "source": spec["url"], algo: expected})
    harvest = platform_spec.get("harvest") or {}
    wanted = {name: exe for name, exe in harvest.get("executables", {}).items() if name in comp.get("tools", [])}
    if wanted:
        manager = harvest["manager"]
        log(f"{comp['id']}: relocating {manager} executables {', '.join(wanted)}")
        if manager == "homebrew":
            relocated = harvest_homebrew(wanted, comp_root, tools, env, licenses)
        elif manager == "apt":
            relocated = harvest_apt(wanted, comp_root, tools, env, licenses)
        elif manager == "msys2":
            relocated = harvest_msys2(wanted, comp_root, tools, env, licenses, harvest["packages"])
        else:
            raise StageError(f"Unknown harvest manager {manager}")
    if comp.get("tessdata"):
        stage_tessdata(sources, comp_root, cache_dir, env, licenses)
    if not tools:
        raise StageError(f"{comp['id']}: no executable is pinned or harvested for {current_platform_key()}")
    if os.name == "nt":
        path_dirs = sorted({Path(entry["path"]).parent.as_posix() for entry in tools.values()})
    else:
        path_dirs = sorted({Path(entry["path"]).parent.as_posix() for entry in tools.values() if entry["path"].startswith("bin/")}) or []
    write_components_notice(comp_root, licenses)
    return {"tools": dict(sorted(tools.items())), "env": env, "path_dirs": path_dirs, "relocated_files": relocated}


