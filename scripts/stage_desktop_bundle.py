SINGLE_VALUE_ENV = {"TESSDATA_PREFIX", "FONTCONFIG_FILE", "FONTCONFIG_PATH", "MAGICK_GHOSTSCRIPT_PATH"}


def merge_component_manifests(installed: dict[str, dict], root_rel: dict[str, str]) -> dict:
    """Combine per-component manifests into one TOOLS_MANIFEST relative to the components root.

    Mirrored by mergeComponentManifests() in electron/components.cjs (installed app).
    """
    tools: dict[str, dict] = {}
    env: dict[str, list[str]] = {}
    path_dirs: list[str] = []
    for comp_id, manifest in installed.items():
        prefix = root_rel[comp_id]
        for name, entry in (manifest.get("tools") or {}).items():
            tools.setdefault(name, {**entry, "path": f"{prefix}/{entry['path']}", "component": comp_id})
        for key, values in (manifest.get("env") or {}).items():
            resolved = [f"{prefix}/{v}" for v in values]
            if key in SINGLE_VALUE_ENV:
                env.setdefault(key, resolved[:1])
            else:
                env.setdefault(key, [])
                env[key] += [v for v in resolved if v not in env[key]]
        path_dirs += [f"{prefix}/{d}" for d in manifest.get("path_dirs") or []]
    if os.name == "nt" and "gswin64c" in tools and "MAGICK_GHOSTSCRIPT_PATH" not in env:
        env["MAGICK_GHOSTSCRIPT_PATH"] = [Path(tools["gswin64c"]["path"]).parent.as_posix()]
    return {"schema_version": 1, "platform": current_platform_key(), "tools": tools, "env": env, "path_dirs": path_dirs}


def probe_tools(root: Path, manifest: dict, base_env: dict | None = None) -> dict:
    env = omni_environment.bundled_tool_environment(root, manifest, base_env or isolated_env())
    groups: dict[str, dict] = {}
    for label, members in omni_environment.NATIVE_GROUPS.items():
        result = {"required": label not in omni_environment.OPTIONAL_NATIVE_GROUPS, "ready": False, "tool": None, "path": None, "version": None}
        for member in members:
            entry = manifest["tools"].get(member)
            if not entry:
                continue
            ok, version = omni_environment.probe_native_tool(str(root / entry["path"]), member, env=env)
            result.update({"tool": member, "path": entry["path"], "version": version, "ready": ok})
            if ok:
                break
        if result["tool"] is not None:
            groups[label] = result
    return groups


def audit_component(comp_root: Path, manifest: dict, extra_markers: list[str] | None = None) -> list[str]:
    """Anything in a component that still depends on the build machine or escapes the component."""
    comp_root = comp_root.resolve()
    problems: list[str] = []
    markers = reloc.build_host_markers(extra_markers)
    for name, entry in (manifest.get("tools") or {}).items():
        exe = comp_root / entry["path"]
        if not exe.is_file():
            problems.append(f"tool {name}: {entry['path']} missing")
        elif comp_root not in exe.resolve().parents:
            problems.append(f"tool {name}: resolves outside the component ({exe.resolve()})")
    if sys.platform == "darwin":
        problems += reloc.audit_macho_tree(comp_root, comp_root)
    elif sys.platform.startswith("linux"):
        relocated = [comp_root / rel for rel in manifest.get("relocated_files", []) if reloc.is_elf(comp_root / rel)]
        problems += reloc.audit_elf_files(relocated, comp_root)
        if manifest.get("kind") == "python-libraries":
            objects = [p for p in comp_root.rglob("*.so*") if reloc.is_elf(p)]
            problems += reloc.audit_elf_files(objects, comp_root, allowed_host=reloc.MANYLINUX_HOST_LIBS)
    elif os.name == "nt":
        for directory in sorted({(comp_root / rel).parent for rel in manifest.get("relocated_files", [])}):
            problems += reloc.audit_pe_dir(directory)
        problems += reloc.audit_binary_markers(sorted(comp_root.rglob("Scripts/*.exe")), markers)
    text_files: list[Path] = [comp_root / COMPONENT_MANIFEST]
    for sub in ("bin", "share", "etc"):
        base = comp_root / sub
        if base.is_dir():
            text_files += [p for p in base.rglob("*") if p.is_file()]
    text_files += list(comp_root.glob("*.cfg")) + list(comp_root.glob("**/site-packages/*.pth"))
    problems += reloc.audit_text_files(text_files, markers)
    return problems


def _tree_size(root: Path) -> int:
    total = 0
    for path in root.rglob("*"):
        try:
            if path.is_file() and not path.is_symlink():
                total += path.stat().st_size
        except OSError:
            pass
    return total


def pack_component(comp_root: Path, archive: Path) -> dict:
    """tar.gz with the component's files at the archive root (symlinks + modes preserved)."""
    archive.parent.mkdir(parents=True, exist_ok=True)
    tmp = archive.with_name(archive.name + ".part")
    with tarfile.open(tmp, "w:gz", compresslevel=6) as tf:
        for path in sorted(comp_root.rglob("*")):
            info = tf.gettarinfo(str(path), arcname=path.relative_to(comp_root).as_posix())
            info.uid = info.gid = 0
            info.uname = info.gname = ""
            if info.isreg():
                with path.open("rb") as handle:
                    tf.addfile(info, handle)
            else:
                tf.addfile(info)
    os.replace(tmp, archive)
    return {"file": archive.name, "sha256": sha256_file(archive), "size": archive.stat().st_size}


def build_components(build_root: Path, out_root: Path, plat: str, sources: dict, cache_dir: Path, only: list[str] | None = None) -> dict:
    platform_spec = sources["platforms"].get(plat)
    if not platform_spec:
        raise StageError(f"No component sources pinned for {plat}; supported: {', '.join(sources['platforms'])}")
    stage = build_root / "components" / plat
    archives = out_root / "components" / plat
    _rmtree(stage)
    _rmtree(archives)
    stage.mkdir(parents=True, exist_ok=True)
    for spec in platform_spec.get("downloads", []):  # build-only helpers (Windows 7zr)
        if spec.get("build_only"):
            algo, expected = digest_of(spec)
            path = download_verified(_spec_urls(spec), algo, expected, cache_dir, spec["id"])
            _SEVENZIP["7zr"] = path
    host_markers = [str(REPO_ROOT), str(build_root.resolve()), str(cache_dir.resolve())]
    version = app_version()
    results: dict[str, dict] = {}
    staged_manifests: dict[str, dict] = {}
    # 7-Zip first: on Windows its 7z.exe extracts the NSIS-packaged tools that follow.
    order = sorted(sources["components"], key=lambda c: {"python-runtime": 0, "python-libraries": 1, "7zip": 2}.get(c["id"], 3))
    for comp in order:
        comp_id = comp["id"]
        if only and comp_id not in only and comp_id != "python-runtime":
            continue
        comp_root = stage / comp_id
        log(f"component {comp_id}: building")
        record: dict = {"id": comp_id, "errors": []}
        try:
            if comp.get("kind") == "python-runtime":
                details = build_python_runtime(comp_root, plat, sources, cache_dir)
                manifest = {"kind": "python-runtime", "python": details["python"], "tools": {}, "env": {}, "path_dirs": []}
                record["details"] = details
            elif comp.get("kind") == "python-libraries":
                comp_root.mkdir(parents=True)
                details = build_python_libraries(comp_root, stage / "python-runtime", cache_dir)
                manifest = {"kind": "python-libraries", "python_path": details["python_path"], "tools": {}, "env": {}, "path_dirs": []}
                record["details"] = details
                if details["failed_imports"]:
                    record["errors"].append("imports failed: " + "; ".join(f"{k} ({v})" for k, v in details["failed_imports"].items()))
                if not details["pip_check_ok"]:
                    record["errors"].append("pip check failed: " + details["pip_check"])
            else:
                comp_root.mkdir(parents=True)
                manifest = {"kind": "native", **build_native_component(comp, comp_root, platform_spec, sources, cache_dir)}
            manifest.update({"schema_version": 1, "id": comp_id, "version": version, "platform": plat})
            (comp_root / COMPONENT_MANIFEST).write_text(json.dumps(manifest, indent=2), encoding="utf-8")
            staged_manifests[comp_id] = manifest
            if manifest["tools"]:
                groups = probe_tools(comp_root, manifest)
                record["groups"] = groups
                broken = [label for label, g in groups.items() if not g["ready"]]
                if broken:
                    record["errors"].append("tools do not run from the component: " + ", ".join(broken))
            audit = audit_component(comp_root, manifest, host_markers)
            if manifest["kind"] == "python-libraries":
                # Optional plugins some wheels ship without their libraries (e.g. mysql-connector's
                # FIDO/Kerberos auth): not a host dependency; reported, never shown as working.
                record["warnings"] = [a for a in audit if ": missing @loader_path/" in a]
                audit = [a for a in audit if a not in record["warnings"]]
                manifest["upstream_missing_libraries"] = [w.replace(str(comp_root.resolve()) + os.sep, "").replace(str(comp_root) + os.sep, "") for w in record["warnings"]]
                (comp_root / COMPONENT_MANIFEST).write_text(json.dumps(manifest, indent=2), encoding="utf-8")
            record["audit"] = audit[:200]
            if audit:
                record["errors"].append(f"audit found {len(audit)} build-host references")
            if not record["errors"]:
                record.update(pack_component(comp_root, archives / f"{comp_id}-{plat}.tar.gz"))
                record["installed_size"] = _tree_size(comp_root)
                log(f"component {comp_id}: packed {record['size'] / 1e6:.1f} MB (installs {record['installed_size'] / 1e6:.0f} MB)")
        except StageError as exc:
            record["errors"].append(str(exc))
        for err in record["errors"]:
            log(f"component {comp_id}: ERROR {err[:1500]}")
        results[comp_id] = record

    # Probe everything together, exactly as an "install all" would see it.
    combined: dict = {}
    if staged_manifests:
        merged = merge_component_manifests(staged_manifests, {cid: cid for cid in staged_manifests})
        combined = probe_tools(stage, merged)
    return {"stage": str(stage), "archives": str(archives), "components": results, "combined_groups": combined}


def write_catalog(build_root: Path, out_root: Path, plat: str, sources: dict, built: dict, base_url: str) -> dict:
    entries = []
    for comp in sources["components"]:
        record = built["components"].get(comp["id"])
        if not record or record.get("errors") or "sha256" not in record:
            continue
        manifest = json.loads((Path(built["stage"]) / comp["id"] / COMPONENT_MANIFEST).read_text(encoding="utf-8"))
        entries.append({
            "id": comp["id"],
            "title": comp["title"],
            "description": comp["description"],
            "kind": manifest["kind"],
            "requires": comp.get("requires", []),
            "recommended": bool(comp.get("recommended")),
            "tools": sorted(manifest.get("tools", {})),
            "version": manifest["version"],
            "file": record["file"],
            "sha256": record["sha256"],
            "size": record["size"],
            "installed_size": record["installed_size"],
        })
    catalog = {
        "schema_version": 1,
        "platform": plat,
        "app_version": app_version(),
        "base_url": base_url,
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "components": entries,
    }
    text = json.dumps(catalog, indent=2)
    (build_root / "components-catalog.json").write_text(text, encoding="utf-8")
    (out_root / "components" / plat).mkdir(parents=True, exist_ok=True)
    (out_root / "components" / plat / "catalog.json").write_text(text, encoding="utf-8")
    return catalog


def stage_bundle(
    download_offline: bool = True,
    with_components: bool = True,
    build_root: Path | None = None,
    out_root: Path | None = None,
    cache_dir: Path | None = None,
    only: list[str] | None = None,
) -> dict:
    build_root = Path(build_root) if build_root is not None else REPO_ROOT / "build"
    out_root = Path(out_root) if out_root is not None else REPO_ROOT / "out"
    build_root.mkdir(parents=True, exist_ok=True)
    cache_dir = Path(cache_dir or os.environ.get("OMNI_DESKTOP_CACHE") or (REPO_ROOT / ".desktop-cache"))
    plat = current_platform_key()
    sources = load_sources()
    errors: list[str] = []
    for legacy in ("python-runtime", "native-tools"):
        _rmtree(build_root / legacy)  # pre-component layouts

    offline_status = ensure_offline_vendor_assets(download_if_missing=download_offline)
    if not offline_status["ready"]:
        errors.append(f"offline assets: {offline_status['verified_count']}/{offline_status['total_count']} verified")
    engine_status = stage_omni_engine(build_root)

    built: dict = {"components": {}}
    catalog: dict = {"components": []}
    if with_components:
        built = build_components(build_root, out_root, plat, sources, cache_dir, only)
        base_url = os.environ.get("OMNI_COMPONENTS_BASE_URL") or DEFAULT_COMPONENTS_BASE_URL.format(version=app_version())
        catalog = write_catalog(build_root, out_root, plat, sources, built, base_url)
        for comp_id, record in built["components"].items():
            errors += [f"{comp_id}: {e}" for e in record.get("errors", [])]
        expected = [c["id"] for c in sources["components"] if not only or c["id"] in only or c["id"] == "python-runtime"]
        missing = [cid for cid in expected if cid not in {e["id"] for e in catalog["components"]}]
        if missing:
            errors.append("components not built: " + ", ".join(missing))
    else:
        _rmtree(build_root / "components-catalog.json")

    manifest = {
        "schema_version": SCHEMA_VERSION,
        "staged_at": datetime.now(timezone.utc).isoformat(),
        "platform": plat,
        "app_version": app_version(),
        "complete": bool(with_components and not only and not errors),
        "errors": errors,
        "build_host_paths": [str(REPO_ROOT), str(build_root.resolve()), str(cache_dir.resolve())],
        "offline_assets": offline_status,
        "omni_engine": engine_status,
        "components": built.get("components", {}),
        "combined_groups": built.get("combined_groups", {}),
        "catalog_entries": len(catalog["components"]),
    }
    (build_root / "BUNDLE_MANIFEST.json").write_text(json.dumps(manifest, indent=2, default=str), encoding="utf-8")
    return manifest


def main() -> int:
    parser = argparse.ArgumentParser(description="Stage the OmniConverter Studio desktop base bundle and build its optional components.")
    parser.add_argument("--engine-only", action="store_true",
                        help="Stage only the base (engine/UI/offline assets); no components. Marked incomplete; cannot be packaged.")
    parser.add_argument("--only", action="append", default=[], help="Build only this component (repeatable; dev loop, marked incomplete)")
    parser.add_argument("--no-download-offline", action="store_true", help="Do not download missing offline browser assets.")
    parser.add_argument("--cache-dir", default=None, help="Download cache (default: .desktop-cache or $OMNI_DESKTOP_CACHE).")
    parser.add_argument("--download-offline", action="store_true", help=argparse.SUPPRESS)
    parser.add_argument("--create-venv", action="store_true", help=argparse.SUPPRESS)
    args = parser.parse_args()

    try:
        manifest = stage_bundle(
            download_offline=not args.no_download_offline,
            with_components=not args.engine_only,
            cache_dir=Path(args.cache_dir) if args.cache_dir else None,
            only=args.only or None,
        )
    except StageError as exc:
        log(f"FAILED: {exc}")
        return 1

    log(f"{manifest['platform']}: offline_assets={manifest['offline_assets']['verified_count']}/{manifest['offline_assets']['total_count']} "
        f"components={manifest['catalog_entries']}/{len(manifest['components']) or 0}")
    for comp_id, record in manifest["components"].items():
        status = "ok" if not record.get("errors") else "FAILED"
        size = f" {record['size'] / 1e6:.0f} MB" if "size" in record else ""
        log(f"  {comp_id}: {status}{size}")
    combined = manifest.get("combined_groups") or {}
    if combined:
        ready = sum(1 for g in combined.values() if g["required"] and g["ready"])
        total = sum(1 for g in combined.values() if g["required"])
        log(f"  all components together: {ready}/{total} required tool groups run")
    if args.engine_only or args.only:
        log("Partial staging finished; the build is marked incomplete and will not be packaged.")
        return 0 if not manifest["errors"] or args.engine_only else 1
    if not manifest["complete"]:
        for error in manifest["errors"]:
            log(f"ERROR: {error[:2000]}")
        return 1
    log("Base bundle and all components complete.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
