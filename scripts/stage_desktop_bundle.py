def digest_of(spec: dict) -> tuple[str, str]:
    for algo, length in (("sha256", 64), ("sha512", 128)):
        value = spec.get(algo)
        if value:
            if len(value) != length or any(c not in "0123456789abcdef" for c in value):
                raise StageError(f"Invalid {algo} pin for {spec.get('url')}")
            return algo, value
    raise StageError(f"No checksum pinned for {spec.get('url')}")


def _ssl_context() -> ssl.SSLContext:
    try:
        import certifi  # type: ignore

        return ssl.create_default_context(cafile=certifi.where())
    except ImportError:
        return ssl.create_default_context()


def download_verified(url, algo: str, expected: str, cache_dir: Path, label: str) -> Path:
    """Download into a content-addressed cache and verify the pinned digest before use.

    `url` may be a list of equivalent official sources (e.g. a redirector plus an archive).
    A source whose bytes do not match the pin is rejected and the next one is tried; the
    stage fails only if no source yields the pinned file.
    """
    urls = [url] if isinstance(url, str) else list(url)
    cache_dir.mkdir(parents=True, exist_ok=True)
    name = urllib.parse.unquote(Path(urllib.parse.urlparse(urls[0]).path).name)
    dest = cache_dir / f"{expected[:16]}-{name}"
    if dest.is_file() and _digest_file(dest, algo) == expected:
        log(f"{label}: cached {name} ({dest.stat().st_size / 1e6:.1f} MB, {algo} verified)")
        return dest
    failures: list[str] = []
    tmp = dest.with_name(dest.name + ".part")
    for index, source_url in enumerate(urls):
        if index:
            tmp.unlink(missing_ok=True)  # a partial file is only resumed from the same source
        failed_attempts = 0
        while failed_attempts < 6:
            before = tmp.stat().st_size if tmp.exists() else 0
            try:
                have = before
                headers = {"User-Agent": "OmniConverter-Desktop-Build/1.0"}
                if have:
                    headers["Range"] = f"bytes={have}-"
                request = urllib.request.Request(source_url, headers=headers)
                with urllib.request.urlopen(request, timeout=60, context=_ssl_context()) as source:
                    served_by = source.geturl()
                    resumed = have and getattr(source, "status", 200) == 206
                    if not resumed:
                        have = 0
                    length = int(source.headers.get("Content-Length") or 0)
                    expected_total = have + length if length else 0
                    log(f"{label}: {'resuming' if resumed else 'downloading'} {served_by}"
                        + (f" ({expected_total / 1e6:.1f} MB, from {have / 1e6:.0f} MB)" if resumed else (f" ({length / 1e6:.1f} MB)" if length else "")))
                    total = have
                    next_report = total
                    with tmp.open("ab" if resumed else "wb") as out:
                        while True:
                            chunk = source.read(1024 * 1024)
                            if not chunk:
                                break
                            out.write(chunk)
                            total += len(chunk)
                            if expected_total and total >= next_report:
                                log(f"{label}: {total * 100 // expected_total}% ({total / 1e6:.0f}/{expected_total / 1e6:.0f} MB)")
                                next_report = total + max(expected_total // 5, 25 * 1024 * 1024)
                if expected_total and total != expected_total:
                    # The server closed the connection early: keep the partial file and resume.
                    raise ConnectionError(f"truncated download ({total} of {expected_total} bytes)")
                actual = _digest_file(tmp, algo)
                if actual != expected:
                    tmp.unlink(missing_ok=True)
                    failures.append(f"{served_by}: {algo} {actual} != pinned {expected}")
                    log(f"{label}: REJECTED {served_by} ({algo} mismatch); trying the next source")
                    break  # a mismatching source is not retried
                os.replace(tmp, dest)
                log(f"{label}: {algo} verified")
                return dest
            except Exception as exc:  # network errors: retry/resume this source
                gained = (tmp.stat().st_size if tmp.exists() else 0) > before
                if not gained:
                    failed_attempts += 1  # attempts that made progress do not count
                log(f"{label}: transfer from {source_url} interrupted ({exc}); "
                    + ("resuming" if gained else f"retry {failed_attempts}/6"))
                if failed_attempts >= 6:
                    failures.append(f"{source_url}: {exc}")
                time.sleep(min(30, 3 * max(1, failed_attempts)))
    tmp.unlink(missing_ok=True)
    raise StageError(f"{label}: no source produced the pinned file:\n  " + "\n  ".join(failures))


def _spec_urls(spec: dict) -> list[str]:
    return [spec["url"], *spec.get("mirrors", [])]


def _rmtree(path: Path) -> None:
    if not path.exists() and not path.is_symlink():
        return

    def onerror(func, target, _exc):
        try:
            os.chmod(target, stat.S_IWRITE | stat.S_IREAD | stat.S_IEXEC)
            func(target)
        except OSError:
            pass

    if path.is_symlink() or path.is_file():
        path.unlink()
    else:
        shutil.rmtree(path, onerror=onerror)


def _run(cmd: list[str], **kwargs) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, check=False, capture_output=True, text=True, errors="replace", **kwargs)


def _run_checked(cmd: list[str], label: str, **kwargs) -> subprocess.CompletedProcess:
    proc = _run(cmd, **kwargs)
    if proc.returncode != 0:
        tail = (proc.stdout + "\n" + proc.stderr).strip()[-4000:]
        raise StageError(f"{label} failed (exit {proc.returncode}): {' '.join(map(str, cmd))}\n{tail}")
    return proc


