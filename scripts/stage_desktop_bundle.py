def runtime_python(runtime_dir: Path) -> Path:
    return runtime_dir / ("python.exe" if os.name == "nt" else "bin/python3")


def runtime_scripts_dir(runtime_dir: Path) -> Path:
    return runtime_dir / ("Scripts" if os.name == "nt" else "bin")


def isolated_env(extra: dict | None = None) -> dict:
    """Environment without Python/pip/venv leakage from the build shell."""
    env = {k: v for k, v in os.environ.items() if not k.upper().startswith(("PYTHON", "PIP_", "VIRTUAL_ENV", "CONDA"))}
    env["PYTHONNOUSERSITE"] = "1"
    env["PYTHONUTF8"] = "1"
    if extra:
        env.update(extra)
    return env


def _extract_tar(archive: Path, dest: Path) -> None:
    dest.mkdir(parents=True, exist_ok=True)
    with tarfile.open(archive) as tf:
        try:
            tf.extractall(dest, filter="tar")
        except TypeError:  # Python without extraction filters
            tf.extractall(dest)


def make_posix_scripts_relocatable(scripts_dir: Path, runtime_dir: Path) -> list[str]:
    """Rewrite pip-generated shebangs (absolute build path) to a relative sh trampoline."""
    changed: list[str] = []
    markers = {str(runtime_dir.resolve()).encode(), str(runtime_dir).encode()}
    for script in sorted(scripts_dir.iterdir()):
        if script.is_symlink() or not script.is_file():
            continue
        data = script.read_bytes()
        if not data.startswith(b"#!"):
            continue
        first, _, rest = data.partition(b"\n")
        if not any(m in first for m in markers):
            continue
        trampoline = (
            b"#!/bin/sh\n"
            b"'''exec' \"$(dirname -- \"$0\")/python3\" \"$0\" \"$@\"\n"
            b"' '''\n"
        )
        script.write_bytes(trampoline + rest)
        changed.append(script.name)
    return changed


def remove_windows_absolute_launchers(scripts_dir: Path, runtime_dir: Path) -> list[str]:
    """pip's Windows .exe launchers embed the build path and cannot be relocated."""
    removed: list[str] = []
    if not scripts_dir.is_dir():
        return removed
    marker = str(runtime_dir.resolve()).lower().encode()
    for launcher in sorted(scripts_dir.glob("*.exe")):
        if marker in launcher.read_bytes().lower():
            launcher.unlink()
            removed.append(launcher.name)
    return removed


PYTHON_IMPORT_PROBE = r"""
import importlib, json, sys, time
mods = json.loads(sys.argv[1])
out = {}
for label, module in mods.items():
    t = time.time()
    try:
        importlib.import_module(module)
        out[label] = {"ok": True, "seconds": round(time.time() - t, 2)}
    except BaseException as exc:
        out[label] = {"ok": False, "error": f"{type(exc).__name__}: {exc}"[:400]}
print(json.dumps({"executable": sys.executable, "prefix": sys.prefix, "version": sys.version.split()[0], "modules": out}))
"""


def probe_python_imports(python_exe: Path, env: dict | None = None, cwd: Path | None = None) -> dict:
    proc = _run(
        [str(python_exe), "-s", "-c", PYTHON_IMPORT_PROBE, json.dumps(omni_environment.PYTHON_IMPORTS)],
        env=env or isolated_env(),
        cwd=str(cwd) if cwd else None,
        timeout=900,
    )
    if proc.returncode != 0:
        raise StageError(f"Python import probe failed: {proc.stderr.strip()[-3000:]}")
    return json.loads(proc.stdout.strip().splitlines()[-1])


def build_python_runtime(comp_root: Path, plat: str, sources: dict, cache_dir: Path) -> dict:
    spec = sources["python"]["platforms"].get(plat)
    if not spec:
        raise StageError(f"No pinned portable Python for {plat}")
    algo, expected = digest_of(spec)
    archive = download_verified(_spec_urls(spec), algo, expected, cache_dir, "python-runtime")
    with tempfile.TemporaryDirectory(dir=comp_root.parent) as tmp:
        _extract_tar(archive, Path(tmp))
        extracted = Path(tmp) / "python"
        if not extracted.is_dir():
            raise StageError("Unexpected python-build-standalone layout (no python/ directory)")
        shutil.move(str(extracted), str(comp_root))
    scripts_dir = runtime_scripts_dir(comp_root)
    if os.name == "nt":
        remove_windows_absolute_launchers(scripts_dir, comp_root)
    else:
        make_posix_scripts_relocatable(scripts_dir, comp_root)
    python_exe = runtime_python(comp_root)
    version = _run_checked([str(python_exe), "-c", "import sys; print(sys.version.split()[0])"], "python version").stdout.strip()
    return {
        "version": version,
        "python": _posix_rel(python_exe, comp_root),
        "source": {"url": spec["url"], algo: expected},
    }


def build_python_libraries(comp_root: Path, runtime_root: Path, cache_dir: Path) -> dict:
    """requirements-local.txt installed with --target into <component>/site-packages."""
    python_exe = runtime_python(runtime_root)
    site = comp_root / "site-packages"
    site.mkdir(parents=True, exist_ok=True)
    env = isolated_env({"PIP_CACHE_DIR": str(cache_dir / "pip"), "PIP_DISABLE_PIP_VERSION_CHECK": "1"})
    log("python-libraries: installing requirements-local.txt for the bundled runtime")
    proc = subprocess.run(
        [str(python_exe), "-s", "-m", "pip", "install", "--no-warn-script-location", "--prefer-binary",
         "--target", str(site), "-r", str(REPO_ROOT / "requirements-local.txt")],
        env=env, check=False,
    )
    if proc.returncode != 0:
        raise StageError("pip install -r requirements-local.txt failed for the bundled runtime")
    # Console-script launchers embed absolute build paths; the engine imports modules instead.
    for scripts in (site / "bin", site / "Scripts"):
        _rmtree(scripts)
    actions: list[str] = []
    if sys.platform == "darwin":
        actions = reloc.relocate_external_macho_deps_in_tree(site, comp_root / "lib")
        actions += reloc.strip_foreign_macho_rpaths(site)
    elif sys.platform.startswith("linux"):
        actions = reloc.bundle_external_elf_deps_in_tree(site, comp_root / "lib")
    if actions:
        log(f"python-libraries: bundled {len(actions)} external native dependencies of installed wheels")
    probe_env = isolated_env({"PYTHONPATH": str(site)})
    imports = probe_python_imports(python_exe, env=probe_env)
    pip_check = _run([str(python_exe), "-s", "-m", "pip", "check"], env=probe_env)
    required = {k: v for k, v in imports["modules"].items() if k not in omni_environment.OPTIONAL_PYTHON_IMPORTS}
    failed = {k: v.get("error") for k, v in required.items() if not v["ok"]}
    return {
        "python_path": ["site-packages"],
        "required_imports_ready": len(required) - len(failed),
        "required_imports_total": len(required),
        "failed_imports": failed,
        "pip_check_ok": pip_check.returncode == 0,
        "pip_check": (pip_check.stdout + pip_check.stderr).strip()[-2000:],
        "native_dependency_actions": actions,
    }


